//   0행: 컬럼명, 1행: 연도 헤더, 2행~: "N. 대분류" 행과 설비 행이 섞인다
// ---------------------------------------------------------------------------
const YEARS = [2021, 2022, 2023, 2024, 2025, 2026, 2027, 2028, 2029, 2030];

// 등급 칸은 연도 수(10)만큼 자리를 차지한다 — 머리글을 한 칸이라도 덜 비워두면
// 뒤의 주기·시행방법 컬럼이 연도 열과 겹쳐 전부 밀린다.
const planHead = () => [
  ["설비구분", "기 기 명", "기기번호", "제작사", "사양",
    "중장기 보수계획(등급)", ...Array(YEARS.length - 1).fill(""),
    "예방점검주기", "정밀점검주기", "시행방법", "준공년도"],
  ["", "", "", "", "", ...YEARS.map(String), "", "", "", ""],
];

/** "N. 대분류" 행 — 파서는 이 행을 만나면 이후 설비들의 대분류로 기억한다 */
const cat = (label) => [label, "", "", "", "", ...YEARS.map(() => ""), "", "", "", ""];

/** 설비 1행. grades = { 연도: "A"|"B"|"C" } */
const item = (name, tag, maker, spec, grades, patrol, cycle, method, completion) => [
  "", name, tag, maker, spec,
  ...YEARS.map((y) => grades[y] || ""),
  patrol, cycle, method, completion,
];

/**
 * 주기에 맞춰 과거·미래 등급을 채운다. 실제 중장기 계획표처럼 주기마다
 * 같은 등급이 반복되고, lastDone 이후 연도에는 계획 등급이 들어간다.
 * 판정에 쓰이는 "마지막 보수연도"는 올해(2026)보다 앞선 등급만 보므로
 * 미래 등급을 채워도 판정은 달라지지 않는다.
 */
const series = (lastDone, cycleYears, grade) => {
  const g = {};
  for (let y = lastDone; y >= YEARS[0]; y -= cycleYears) g[y] = grade;
  for (let y = lastDone + cycleYears; y <= YEARS[YEARS.length - 1]; y += cycleYears) g[y] = grade;
  return g;
};

/** 주기·마지막 보수연도로 설비 1행을 만든다 (정상 데이터용 단축 헬퍼) */
const plan = (name, tag, maker, spec, lastDone, cycleYears, grade, completion, method = "O/H") =>
  item(name, tag, maker, spec, series(lastDone, cycleYears, grade),
    "월 1회", `${cycleYears}년`, method, completion);

const write = (dir, fileName, sheets) => {
  const wb = XLSX.utils.book_new();
  for (const [sheetName, rows] of sheets) {
    XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet(rows), sheetName);
  }
  XLSX.writeFile(wb, path.join(dir, fileName));
  console.log("  " + path.relative(outDir, path.join(dir, fileName)));
};

