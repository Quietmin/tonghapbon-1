const TASK_HEAD = ["명칭", "규격", "수량", "단위", "Tag No.", "작업시작일", "작업종료일", "비고"];

/**
 * 공종 시트 하나 — 설비 행 + 공통 작업 + 소계 행.
 * 소계는 실제 설계내역서처럼 넣는다 (업로드 분석이 "제외"로 세어야 한다).
 */
const taskSheet = (items, extra = []) => {
  const rows = [TASK_HEAD];
  for (const e of items) {
    const [suffix, qty, unit, phase] = e.task;
    const [s, f] = schedule(phase);
    rows.push([e.name + suffix, e.spec, qty, unit, e.tag, s, f, ""]);
  }
  for (const [name, spec, qty, unit, phase, note] of extra) {
    const [s, f] = schedule(phase);
    rows.push([name, spec, qty, unit, "", s, f, note || ""]);
  }
  rows.push(["소계", "", "", "", "", "", "", ""]);
  return rows;
};

