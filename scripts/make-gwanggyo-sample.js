const isFixed = (e) => /^\d+년$/.test(e.cycleRaw);
const isDue = (e) => isFixed(e) && e.last != null && e.last + e.cycle <= THIS_YEAR;
const toStatement = (e) => e.method === "O/H" && isDue(e) && e.task;

// ---------------------------------------------------------------------------
// 작업기간 — 공정단계별 창 안에서 순서대로 엇갈려 배치한다
//   단계 창·작업일수는 68일(0~67일째) 기준으로 짜 두었고, 실제 계약기간 길이에 맞춰
//   비례로 줄이거나 늘린다 — 계약기간을 바꿔도 모든 작업이 기간 안에 들어간다.
// ---------------------------------------------------------------------------
const PHASE = {
  prep: [0, 7], // 가설·준비
  dis: [4, 34], // 분해
  insp: [6, 50], // 점검·측정
  cal: [10, 52], // 교정
  asm: [36, 60], // 조립
  test: [56, 67], // 시험·시운전
};
const DUR = { prep: 6, dis: 14, insp: 9, cal: 7, asm: 10, test: 6 };
const BASE_LAST_DAY = 67;
const PERIOD_LAST_DAY = Math.round((Date.parse(PERIOD.end) - Date.parse(PERIOD.start)) / 86400000);
const fit = (n) => Math.round((n * PERIOD_LAST_DAY) / BASE_LAST_DAY);

const addDays = (iso, n) => {
  const d = new Date(iso + "T00:00:00Z");
  d.setUTCDate(d.getUTCDate() + n);
  return d.toISOString().slice(0, 10);
};

const counters = {};
const schedule = (phase) => {
  const from = fit(PHASE[phase][0]);
  const to = fit(PHASE[phase][1]);
  const dur = Math.max(2, fit(DUR[phase]));
  const k = (counters[phase] = (counters[phase] ?? -1) + 1);
  const span = to - from - dur;
  const startOff = from + ((k * 2) % Math.max(span, 1));
  return [addDays(PERIOD.start, startOff), addDays(PERIOD.start, Math.min(startOff + dur, to))];
};

