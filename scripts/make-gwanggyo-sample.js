/**
 * 주기에 맞춰 등급을 채운다.
 * 과거: lastDone부터 주기만큼 거슬러 올라간다.
 * 미래: 다음 도래연도부터 채우되, 이미 지난 해(올해 이전)에는 넣지 않는다 —
 *       파서는 올해 이전의 등급을 전부 "보수 실적"으로 읽으므로, 거기에 계획 등급을
 *       넣으면 기한초과 설비가 도래로 바뀐다.
 */
const series = (lastDone, cycle, grade) => {
  const g = {};
  if (lastDone == null) return g;
  for (let y = lastDone; y >= YEARS[0]; y -= cycle) g[y] = grade;
  let next = lastDone + cycle;
  while (next < THIS_YEAR) next += cycle;
  for (let y = next; y <= YEARS[YEARS.length - 1]; y += cycle) g[y] = grade;
  return g;
};

/**
 * 설비 1건 정의.
 *   last·cycle — 마지막 보수연도·정밀점검주기(년). 2026 판정이 여기서 정해진다
 *   method     — "O/H"만 수량산출서 대상. 그 밖(경상정비·용역)은 참고 탭
 *   cycleRaw   — 주기 문구를 직접 줄 때 (조건부·필요시 등 "선택" 판정용)
 *   task       — 수량산출서로 옮길 때의 [작업명 꼬리, 수량, 단위, 공정단계]
 *                공정단계: prep(가설) dis(분해) insp(점검) cal(교정) asm(조립) test(시험)
 */
